def test_split_url_and_redact():
    conninfo, schema = pgcompat.split_url("postgresql://u:secret@db:5432/arch?schema=ma_prod&sslmode=require")
    assert schema == "ma_prod" and "schema=" not in conninfo and "sslmode=require" in conninfo
    assert pgcompat.split_url("postgres://u@db/arch")[1] == "mailarchiver"
    assert "secret" not in pgcompat.redact("postgresql://u:secret@db/arch")
    with pytest.raises(ValueError):
        pgcompat.split_url("postgresql://u@db/arch?schema=Bad-Name")


def test_translate_dml():
    tr = pgcompat._translate_static("SELECT * FROM t WHERE a LIKE ? AND b IS ? AND c IS NOT ? AND d LIKE '%x'")
    assert "ILIKE %s" in tr.sql and "IS NOT DISTINCT FROM %s" in tr.sql and "IS DISTINCT FROM %s" in tr.sql
    assert "'%%x'" in tr.sql                       # % в строке — для psycopg удвоен
    assert "GREATEST(a, 1)" in pgcompat._translate_static("SELECT MAX(a, 1) FROM t").sql
    assert "MAX(a)" in pgcompat._translate_static("SELECT MAX(a) FROM t").sql
    assert "AS BIGINT" in pgcompat._translate_static("SELECT CAST(x AS INTEGER) FROM t").sql
    tr = pgcompat._translate_static("INSERT OR IGNORE INTO t(a, b) VALUES(?, ?)")
    assert tr.conflict == "ignore" and tr.table == "t" and tr.insert_cols == ["a", "b"]
    tr = pgcompat._translate_static("SELECT name FROM users WHERE user = ? -- user")
    assert '"user" = %s' in tr.sql


def test_ddl_types_and_foreign_keys():
    stmt = ("CREATE TABLE IF NOT EXISTS x (\n id INTEGER PRIMARY KEY AUTOINCREMENT, -- номер, а тут запятая\n"
            " owner INTEGER REFERENCES users(id) ON DELETE SET NULL,  -- кто\n data BLOB, k REAL,\n"
            " FOREIGN KEY(owner) REFERENCES accounts(id) ON DELETE CASCADE\n)")
    out = pgcompat.ddl_types(stmt)
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in out and "BYTEA" in out and "DOUBLE PRECISION" in out
    table, fks = pgcompat.split_foreign_keys(out)
    assert "REFERENCES" not in table and "FOREIGN" not in table
    assert [(t, c) for t, c, _ in fks] == [("x", "owner"), ("x", "owner")]
    assert fks[0][2].startswith("REFERENCES users(id)") and "CASCADE" in fks[1][2]


def test_trigger_translation():
    sql = ("CREATE TRIGGER IF NOT EXISTS t_ad AFTER DELETE ON messages WHEN old.size > 0 BEGIN "
           "UPDATE totals SET n = n - 1 WHERE id = old.account_id; END")
    out = "\n".join(pgcompat.trigger_ddl(sql))
    assert "CREATE OR REPLACE FUNCTION ma_trg_t_ad()" in out and "RETURNS trigger" in out
    assert "IF old.size > 0 THEN" in out and "AFTER DELETE ON messages FOR EACH ROW" in out


def test_search_tsvector_and_query():
    from mailarchiver import search
    vec = search.tsvector_text({"subject": "Счёт на оплату", "addrs": "ivanov@corp.test", "attach": "", "body": "Café"})
    assert "'счет':1A" in vec and "'ivanov':5B" in vec and "'cafe':" in vec and "D" in vec
    assert search.build_tsquery('тема:счет "на оплату" ivanov@corp') == \
        "'счет':*A & ('на' <-> 'оплату') & ('ivanov' <-> 'corp':*)"
    snip = search.make_snippet({"subject": "Счёт на оплату № 15", "addrs": "", "attach": "", "body": ""}, "счет")
    assert snip.startswith("\x02Счёт\x03")


