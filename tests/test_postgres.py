@needs_pg
def test_services_on_postgres(services):
    assert services.db.is_pg and services.db.dialect == "postgresql"
    from mailarchiver import models
    acc_id = services.db.create_account(models.Account(name="Иванов", host="h", username="ivanov@corp.test",
                                                       password="p"))
    assert services.db.get_account(acc_id).username == "ivanov@corp.test"
    assert services.db.scalar("SELECT COUNT(*) FROM accounts WHERE username = ? COLLATE NOCASE",
                              ("IVANOV@CORP.TEST",)) == 1
    assert services.db.size_bytes() > 0


def _sqlite_archive(tmp_path, monkeypatch):
    """Каталог данных с базой SQLite (служба на SQLite) и парой писем в индексе поиска."""
    from mailarchiver import models
    from mailarchiver.config import load_config
    from mailarchiver.service import Services
    monkeypatch.delenv("MA_TEST_PG", raising=False)
    data = tmp_path / "sqlite-data"
    data.mkdir()
    monkeypatch.setenv("MAILARCHIVER_DATA", str(data))
    cfg = load_config()
    svc = Services(cfg)
    svc.setup()
    db = svc.db
    acc = db.create_account(models.Account(name="Бухгалтерия", host="h", username="buh@corp.test", password="p"))
    emp = db.execute("INSERT INTO employees(full_name, email, account_id, created_at) VALUES(?, ?, ?, ?)",
                     ("Петрова", "buh@corp.test", acc, "2026-01-01T00:00:00Z")).lastrowid
    db.execute("UPDATE accounts SET employee_id=? WHERE id=?", (emp, acc))
    for i, subject in enumerate(("Счёт на оплату № 15", "Акт сверки")):
        db.execute("INSERT INTO messages(account_id, folder, uidvalidity, uid, message_id, subject, from_addr, "
                   "internaldate, size, stored_path, sha256) VALUES(?,?,?,?,?,?,?,?,?,?,?)",
                   (acc, "INBOX", 1, i + 1, f"<m{i}@x>", subject, "boss@corp.test", f"2026-01-0{i + 1}T10:00:00Z",
                    1000 + i, "", f"h{i}"))
    from mailarchiver import search
    search.index_pending(svc)
    svc.stop()
    return cfg, acc


@needs_pg
def test_db_migrate_sqlite_to_postgres(tmp_path, monkeypatch):
    from mailarchiver import dbmigrate, search
    from mailarchiver.database import Database
    cfg, acc = _sqlite_archive(tmp_path, monkeypatch)
    url = PG + ("&" if "?" in PG else "?") + "schema=t_migrate_" + os.urandom(3).hex()
    report = dbmigrate.migrate(cfg.db_path, url)
    assert report["ok"], report
    assert report["tables"]["messages"] == 2 and report["tables"]["accounts"] == 1
    assert report["tables"][search.FTS_TABLE] == 2
    db = Database(url, None)
    try:
        assert db.scalar("SELECT employee_id FROM accounts WHERE id=?", (acc,))
        # номера продолжаются после перенесённых
        new_id = db.execute("INSERT INTO messages(account_id, folder, uidvalidity, uid, message_id, subject, "
                            "from_addr, internaldate, size, stored_path, sha256) VALUES(?,?,?,?,?,?,?,?,?,?,?)",
                            (acc, "INBOX", 1, 9, "<m9@x>", "Новое", "a@b", "2026-02-01T00:00:00Z", 1, "", "fp9")).lastrowid
        assert new_id == 3
        # счётчики не пересчитывались дважды: триггеры при переносе выключены
        assert db.count_messages() == 3
        # повторный перенос в непустую схему — отказ
        from mailarchiver.errors import ConfigError
        with pytest.raises(ConfigError):
            dbmigrate.migrate(cfg.db_path, url)
    finally:
        schema = pgcompat.split_url(url)[1]
        db.execute(f"DROP SCHEMA {schema} CASCADE")
        db.close_all()


@needs_pg
@pytest.mark.skipif(not shutil.which("pg_dump") or not shutil.which("psql"), reason="нет pg_dump/psql")
def test_pg_snapshot_and_restore(services, tmp_path):
    from mailarchiver import models
    from mailarchiver.replica import snapshots
    services.db.create_account(models.Account(name="До снимка", host="h", username="a@b", password="p"))
    info = snapshots.make_snapshot(services, keep=3)
    assert info["name"].endswith(".sql.gz") and snapshots.list_snapshots(services.cfg)[0]["kind"] == "postgresql"
    with gzip.open(info["path"], "rb") as fh:
        assert snapshots._PG_DUMP_END in fh.read()
    services.db.create_account(models.Account(name="После снимка", host="h", username="c@d", password="p"))
    url = services.cfg.db_url
    services.db.close_all()
    broken = tmp_path / "broken.sql.gz"
    with gzip.open(info["path"], "rb") as src, gzip.open(broken, "wb") as dst:
        dst.write(src.read()[:-300])
    from mailarchiver.errors import StorageError
    with pytest.raises(StorageError, match="оборван"):
        snapshots.restore_pg_snapshot(str(broken), url, None)
    from mailarchiver.database import Database
    db = Database(url, None)
    try:
        assert len(db.list_accounts()) == 2                 # оборванная выгрузка ничего не изменила
        db.close_all()
        assert snapshots.restore_pg_snapshot(info["path"], url, None) > 0
        assert [a.name for a in db.list_accounts()] == ["До снимка"]
        # снимок другой схемы разворачивается под именем схемы службы (если той схемы в базе нет)
        target = url.replace("schema=", "schema=r_")
        db.execute(f"ALTER SCHEMA {pgcompat.split_url(url)[1]} RENAME TO {pgcompat.split_url(target)[1]}x")
        db.close_all()
        snapshots.restore_pg_snapshot(info["path"], target, None)
        other = Database(target, None)
        assert [a.name for a in other.list_accounts()] == ["До снимка"]
        other.execute(f"DROP SCHEMA {pgcompat.split_url(target)[1]}x CASCADE")
        other.execute(f"DROP SCHEMA {pgcompat.split_url(target)[1]} CASCADE")
        other.close_all()
    finally:
        db.close_all()
