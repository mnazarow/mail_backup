"""
Групповые действия с ящиками на почтовом сервере (раздел «Ящики на сервере»).

В отличие от групповых действий раздела «Почтовые ящики», которые работают с
архивом, здесь меняется сам почтовый сервер:

* учётные записи Axigen — через CLI администратора (вход и пароли, службы,
  квоты, псевдонимы, контактные данные, создание списком, удаление);
* папки и письма в ящиках любого сервера — по IMAP, с паролем ящика или входом
  администратора почты (очистка корзины и спама, удаление и перенос старых
  писем, отметка «прочитано», создание, переименование и удаление папок).

Порядок у каждого действия один: проверка (ничего не меняет) → подтверждение →
одно задание «Действия с ящиками на сервере», которое обходит ящики по одному и
перед каждым изменением ещё раз проверяет условия. Всё, что удаляет письма или
учётные записи, выполняется только при полном архиве: каждое удаляемое письмо
должно быть в архиве (и его файл — на диске), иначе папка или ящик пропускается.

Модули: :mod:`.targets` — ящики на сервере; :mod:`.base` — описание действий,
проверка и запуск; :mod:`.axigen_ops` и :mod:`.imap_ops` — сами действия;
:mod:`.jobs` — задание очереди; :mod:`.secrets` — одноразовая выдача паролей;
:mod:`.report` — отчёт о ящиках.
"""
